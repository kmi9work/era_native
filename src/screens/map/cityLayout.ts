/** Нормализация имени города для поиска в манифесте. */
export const normalizeCityName = (name: string): string =>
  (name || '')
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/-/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();

/** Раскладка подписи города; для неизвестного города — null (клиент ставит дефолт). */
export const labelLayoutFor = (name: string): CityLabelLayout | null =>
  CITY_LABEL_LAYOUT[normalizeCityName(name)] ?? null;
